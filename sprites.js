/* ---------------- renderer ---------------- */
const pixCache = {};

function pixURL(kind, id) {
  const key = kind + ":" + id;
  if (key in pixCache) return pixCache[key];
  let url = null;
  try {
    const rows = PIX[kind] && PIX[kind][id];
    if (rows) {
      const h = rows.length, w = rows[0].length;
      const cv = document.createElement("canvas");
      cv.width = w; cv.height = h;
      const ctx = cv.getContext("2d");
      for (let y = 0; y < h; y++) {
        const row = rows[y];
        for (let x = 0; x < w; x++) {
          const ch = row[x];
          if (ch !== "." && ch !== " " && PIX_PAL[ch]) {
            ctx.fillStyle = PIX_PAL[ch];
            ctx.fillRect(x, y, 1, 1);
          }
        }
      }
      url = cv.toDataURL();
    }
  } catch (e) {
    url = null; // no canvas (old browser / tests) → callers fall back to emoji
  }
  pixCache[key] = url;
  return url;
}

function pixImg(kind, id, cls) {
  const u = pixURL(kind, id);
  return u ? `<img class="pix ${cls}" src="${u}" alt="">` : "";
}
